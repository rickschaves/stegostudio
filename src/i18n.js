// Detecta idioma: pt se sistema for português, senão inglês (padrão).
let LANG = (navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';

// Retorna a string traduzida para a chave no idioma ativo.
function t(key) {
  return (I18N[LANG] && I18N[LANG][key] !== undefined) ? I18N[LANG][key] : (I18N.en[key] || key);
}

// Traduz o nome interno de um modo de extração LSB (sempre em PT no código)
// para o idioma ativo. Mantém o valor interno estável para a lógica.
function translateMode(mode) {
  const map = {
    'canal B': 'modeChannelB', 'canal R': 'modeChannelR', 'canal G': 'modeChannelG',
    'canal A': 'modeChannelA', 'todos os canais': 'modeAllChannels',
    'RGB intercalado': 'modeRGBInterleaved',
  };
  return map[mode] ? t(map[mode]) : mode;
}

// Aplica as traduções a todos os elementos com data-i18n.
// data-i18n          → textContent
// data-i18n-html     → innerHTML (para strings com <b>, etc.)
// data-i18n-ph       → placeholder
function applyTranslations() {
  document.documentElement.lang = (LANG === 'pt') ? 'pt-BR' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });
  // Aviso de calibração: respeita o interruptor CALIBRATION_MODE
  const calib = document.querySelector('.calib-banner');
  if (calib) calib.style.display = CALIBRATION_MODE ? 'flex' : 'none';
  initTicker();
}

// Troca o idioma e re-renderiza.
function setLang(lang) {
  LANG = lang;
  applyTranslations();
  if (typeof updateEncMessageModalCount === 'function') updateEncMessageModalCount();
  // Se um aviso de chave está ativo, applyTranslations restaura a hint padrão;
  // reaplica o texto do aviso no novo idioma sem reiniciar o timer.
  if (typeof refreshKeyFlashText === 'function') refreshKeyFlashText();
  const btnEn = document.getElementById('lang-en');
  const btnPt = document.getElementById('lang-pt');
  if (btnEn && btnPt) {
    btnEn.classList.toggle('active', lang === 'en');
    btnPt.classList.toggle('active', lang === 'pt');
  }
  // Reaplica o texto traduzido aos terminais sem perder o estado atual
  redrawTerminals();
  // Re-renderiza os resultados da análise (módulos, badges, nomes) no novo idioma.
  // Os módulos são HTML gerado dinamicamente, então precisam ser refeitos.
  // Re-renderize apenas o resultado da geração corrente; uma troca de idioma
  // não pode restaurar um relatório invalidado por uma análise mais recente.
  if (lastRenderArgs && lastRenderArgs.gen === analysisGeneration) {
    const resultsVisible = document.getElementById('results-area')?.classList.contains('visible');
    renderResults(lastRenderArgs.report, lastRenderArgs.decodedMsg, lastRenderArgs.decodeStatus, {passwordIgnored:!!lastRenderArgs.passwordIgnored,recoveredFile:lastRenderArgs.recoveredFile||null});
    // renderResults altera visibilidade; restaure explicitamente o estado que
    // estava ativo antes da tradução, inclusive o caso oculto.
    document.getElementById('results-area')?.classList.toggle('visible', !!resultsVisible);
  }
}

